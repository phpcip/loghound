    /** The command that finishes the job, with this installation's real path. */
    public static function shellCommand(string $root): string
    {
        return 'sudo ' . rtrim($root, '/') . '/install/uninstall.sh';
    }

    /** The one line that stops ingestion first, which is the honest thing to do before this. */
    public static function stopCommand(): string
    {
        return 'sudo systemctl stop loghound-tail.service loghound-score.timer loghound-retention.timer';
    }

    /**
     * Delete everything under `var/`, keeping the directory itself.
     *
     * THE DIRECTORY STAYS ON PURPOSE. The installer is what the operator lands on next, and the
     * first thing it does is mint a token into `var/`. On a normal installation the tree is
     * root-owned and only `var/` is writable by the service user, so removing `var/` would
     * leave the panel process unable to recreate it and the operator unable to reach the
     * installer at all. Emptying it achieves the whole of what the boundary asks for.
     *
     * THE READER'S CURSORS ARE THE POINT, not a side effect. `var/state.db` holds
     * `(dev, inode, offset)` per source. An uninstall that deleted the indexes and left those
     * behind would leave the daemon believing it had already read those bytes, so a rebuilt
     * index would hold only traffic from the moment of the rebuild onwards and the history
     * before it would be unreachable even though the files are still on disk.
     *
     * `$keep` NAMES THE FILES THE RUN IS STANDING ON. A panel-driven teardown is executed one
     * step per request, through a job whose progress lives in `var/panel-jobs.db` and whose
     * owner lives in a session file under `var/sessions`. A wipe that took those with it would
     * destroy the record of its own progress mid-run, and the operator would be told their
     * operation no longer exists on a machine that had just deleted its indexes. The closing
     * step removes what was kept; see Panel\Settings.
     *
     * @param array<int,string> $keep Basenames left alone, matched exactly.
     * @return array{removed:int,kept:array<int,string>,failed:array<int,string>}
     */
    public static function wipeState(Config $cfg, array $keep = []): array
    {
        $dir = self::ownVarDir($cfg);
        if ($dir === '' || !is_dir($dir)) {
            return ['removed' => 0, 'kept' => [], 'failed' => []];
        }

        $removed = 0;
        $kept    = [];
        $failed  = [];
        foreach (self::entries($dir) as $path) {
            $name = basename($path);
            if (in_array($name, $keep, true)) {
                $kept[] = $name;
                continue;
            }
            if (self::remove($path)) {
                $removed++;
            } else {
                $failed[] = $name;
            }
        }

        return ['removed' => $removed, 'kept' => $kept, 'failed' => $failed];
    }

    /**
     * Remove named entries that a previous wipe was told to keep.
     *
     * The other half of `$keep`. Called by the closing step of a panel run, once nothing is
     * standing on them any more.
     *
     * @param array<int,string> $names Basenames under `var/`.
     * @return array{removed:array<int,string>,failed:array<int,string>}
     */
    public static function wipeRemaining(Config $cfg, array $names): array
    {
        $dir = self::ownVarDir($cfg);
        if ($dir === '') {
            return ['removed' => [], 'failed' => []];
        }
        $removed = [];
        $failed  = [];

        foreach ($names as $name) {
            if (!is_string($name) || $name === '' || $name === '.' || $name === '..'
                || str_contains($name, '/')
            ) {
                continue;
            }
            $path = $dir . '/' . $name;
            if (!file_exists($path) && !is_link($path)) {
                continue;
            }
            if (self::remove($path)) {
                $removed[] = $name;
            } else {
                $failed[] = $name;
            }
        }

        return ['removed' => $removed, 'failed' => $failed];
    }

    /**
     * Make sure PHP still has somewhere to write this request's session.
     *
     * A panel-driven run empties `var/`, and on the shipped PHP-FPM pool `session.save_path` is
     * `var/sessions`. With the directory gone, PHP's write at shutdown fails silently and the
     * one-time setup grant this run just issued is lost — which locks the operator out of the
     * installer they are about to be sent to, on a machine whose configuration has just been
     * deleted. So the directory is recreated, empty, at 0700.
     *
     * This is not a hole in the boundary: what is recreated holds no Loghound data, and the one
     * file that lands in it afterwards is the operator's own session carrying that grant. The
     * shell uninstaller removes the tree and everything in it.
     *
     * `$path` DEFAULTS TO THE RUNNING PROCESS'S SAVE PATH and exists so the suite can exercise
     * this at all: session ini settings cannot be changed once output has been sent, which under
     * the CLI runner is always, so a test has no way to make `session_save_path()` say anything.
     * It is not a hole — the path is still refused unless it is inside the var directory this
     * configuration can prove it owns, so the only thing a caller can choose is which directory
     * under `var/` gets recreated.
     *
     * @return string The path, or '' when sessions are not stored under var/.
     */
    public static function ensureSessionDir(Config $cfg, ?string $path = null): string
    {
        $path = $path ?? (string) session_save_path();
        if ($path === '' || str_contains($path, ';')) {
            return '';
        }

        $var = self::ownVarDir($cfg);
        if ($var === '' || !str_starts_with($path, $var . '/')) {
            return '';
        }
        if (!is_dir($path) && !@mkdir($path, 0700, true) && !is_dir($path)) {
            return '';
        }

        return $path;
    }

    /**
     * Delete the configuration and every sibling that holds a copy of its secrets.
     *
     * `config/.loghound.*.tmp` is the same file mid-write: Config::save() writes a private temp
     * file and renames it, so a crash between the two leaves a complete second copy of every
     * secret. `config/tls-*.key` is the self-signed private key install.sh generated. Neither
     * is hypothetical and neither is covered by removing one named file.
     *
     * LAST, ALWAYS. The API key that authorises the index deletion lives in here; purge first
     * and the operator is left with two orphaned indexes they can no longer name from this box.
     *
     * @return array{removed:array<int,string>,failed:array<int,string>}
     */
    public static function wipeConfig(Config $cfg): array
    {
        $path = $cfg->path();
        $dir  = dirname($path);

        if (self::ownVarDir($cfg) === '') {
            return ['removed' => [], 'failed' => [basename($path)]];
        }

        $targets = [$path];
        foreach ([$dir . '/.loghound.*.tmp', $dir . '/tls-*.key'] as $pattern) {
            foreach (glob($pattern) ?: [] as $extra) {
                $targets[] = $extra;
            }
        }

        $removed = [];
        $failed  = [];
        foreach ($targets as $target) {
            if (!file_exists($target)) {
                continue;
            }
            if (self::remove($target)) {
                $removed[] = basename($target);
            } else {
                $failed[] = basename($target);
            }
        }

        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }

        return ['removed' => $removed, 'failed' => $failed];
    }

    /**
     * The `var/` that belongs to THIS configuration, or '' when it cannot be proved to.
     *
     * THE FAILURE THIS FAILS CLOSED ON. Config::varDir() answers `<root>/var` when the
     * configuration sits in `<root>/config/`, and falls back to the var directory of the
     * INSTALLED TREE for any other layout — which is right for a Config that was never loaded
     * from a real file, and catastrophic for a caller whose next move is to delete everything
     * in the directory it names. A stray Config object must not be able to empty the running
     * installation's state.
     *
     * So the relationship is required rather than assumed: the configuration lives in a
     * directory called `config`, and the var directory is its sibling. That is the shape every
     * Loghound installation has, and anything else here is a caller that has not proved which
     * installation it is talking about.
     */
    private static function ownVarDir(Config $cfg): string
    {
        $configDir = dirname($cfg->path());
        if (basename($configDir) !== 'config') {
            return '';
        }

        $expected = dirname($configDir) . '/var';

        return rtrim($cfg->varDir(), '/') === $expected ? $expected : '';
    }

    /**
     * Direct children of a directory, symlinks included and never followed.
     *
     * @return array<int,string>
     */
    private static function entries(string $dir): array
    {
        $out = [];
        foreach ((array) scandir($dir) as $entry) {
            if ($entry === '.' || $entry === '..' || !is_string($entry)) {
                continue;
            }
            $out[] = $dir . '/' . $entry;
        }

        return $out;
    }

    /**
     * Remove one path, recursing into a real directory and never through a symlink.
     *
     * A symlink is unlinked, not followed: `var/sessions` pointed somewhere else by an operator
     * — or by anything that can write in `var/` — must not turn an empty-the-directory into a
     * delete of whatever it aims at.
     */
    private static function remove(string $path): bool
    {
        if (is_link($path)) {
            return @unlink($path);
        }
        if (is_dir($path)) {
            $ok = true;
            foreach (self::entries($path) as $child) {
                $ok = self::remove($child) && $ok;
            }

            return @rmdir($path) && $ok;
        }

        return @unlink($path);
    }
}
