     *
     * @var array<int,string>
     */
    public const PANEL_STEPS = ['ownership', 'delete', 'absence', 'data', 'report'];

    /**
     * The word the operator has to type before any of this happens.
     *
     * A typed word rather than a second button, because the consequences above it are long and
     * the point is that they get read. It is compared case-insensitively after trimming, so an
     * operator who typed it with a trailing space is not told "no" for the wrong reason.
     */
    public const CONFIRM_WORD = 'DELETE EVERYTHING';

    /**
     * How long a confirmed teardown stays armed, in seconds.
     *
     * Fifteen minutes: long enough to read the card again and press the button, short enough
     * that a browser left open on a shared machine is not still holding permission to destroy
     * the installation an hour later. It is spent when the run starts, so this is a ceiling.
     */
    private const ARM_TTL = 900;

    /** Session key holding a confirmed, unspent teardown. */
    private const ARM_KEY = 'lh_teardown_armed';

    /**
     * Record that this browser has typed the word and produced a current second factor.
     *
     * THE ARM IS THE CONFIRMATION, AND IT LIVES IN THE SESSION AND NOWHERE ELSE. There is no
     * cookie, header, hidden field or URL parameter that carries it, so the proof cannot be
     * replayed from a link and cannot be forged by anything that can reach the endpoint. It is
     * separate from the job that does the work for one reason: the job endpoint is polled, and
     * a confirmation attached to a poll would be a confirmation that has to be re-presented, or
     * re-checked, on every one of them.
     */
    public static function arm(): void
    {
        \Loghound\Security::startSession();
        $_SESSION[self::ARM_KEY] = time();
    }

    /**
     * Is a confirmed teardown waiting to be started, without consuming it?
     *
     * Used by the card so it can render the run. Rendering must not spend the arm: a reload of
     * the page between confirming and starting would otherwise silently disarm it.
     */
    public static function isArmed(): bool
    {
        $at = $_SESSION[self::ARM_KEY] ?? null;

        return is_int($at) && $at > 0 && (time() - $at) <= self::ARM_TTL;
    }

    /**
     * Spend the arm, if this session holds one that is still good.
     *
     * ONE-TIME. Removed whether or not it was still valid, so an expired one cannot sit in a
     * session being re-tested and a valid one authorises exactly one run.
     */
    public static function spendArm(): bool
    {
        \Loghound\Security::startSession();

        $at = $_SESSION[self::ARM_KEY] ?? null;
        unset($_SESSION[self::ARM_KEY]);

        return is_int($at) && $at > 0 && (time() - $at) <= self::ARM_TTL;
    }

    /** Drop any arm this session holds, without spending it. */
    public static function disarm(): void
    {
        \Loghound\Security::startSession();
        unset($_SESSION[self::ARM_KEY]);
    }

    /** Session key recording that a run has been started from this browser. */
    private const RUNNING_KEY = 'lh_teardown_running';

    /**
     * How long a started run keeps the card showing the run rather than the confirmation.
     *
     * An hour, which is far longer than a teardown takes and is bounded so a session that
     * watched one fail does not show a stale progress panel for ever.
     */
    private const RUNNING_TTL = 3600;

    /**
     * Remember that this browser started a run.
     *
     * THE PROBLEM THIS SOLVES. The arm is spent the moment the run begins, so an operator who
     * reloaded the page mid-teardown used to be shown the confirmation form again — a form
     * asking whether to start something that was already running, on a page with no sign of the
     * operation in progress. This is what lets the card reattach to it instead.
     *
     * It authorises nothing. Only the arm does, and it is gone by the time this is set.
     */
    public static function markRunning(): void
    {
        \Loghound\Security::startSession();
        $_SESSION[self::RUNNING_KEY] = time();
    }

    /** Did this browser start a run recently enough to still be watching it? */
    public static function isRunning(): bool
    {
        $at = $_SESSION[self::RUNNING_KEY] ?? null;

        return is_int($at) && $at > 0 && (time() - $at) <= self::RUNNING_TTL;
    }

    /** The label of one step, by id. */
    public static function label(string $id): string
    {
        return self::STEPS[$id] ?? $id;
    }

    /** Is this a step the panel can carry out on its own? */
    public static function isPanelStep(string $id): bool
    {
        return in_array($id, self::PANEL_STEPS, true);
    }

